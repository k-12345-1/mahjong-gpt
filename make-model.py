"""Cut dragon.glb into the two base64 script modules the artifact can serve.

The split is on a 3-byte boundary so each piece is base64 in its own right and the
decoded pieces join back into the original byte for byte -- no padding in the middle.
"""
import base64, sys, hashlib
src, n = sys.argv[1], 2
raw = open(src, 'rb').read()
step = ((len(raw) + n - 1) // n + 2) // 3 * 3
for i in range(n):
    chunk = raw[i * step:(i + 1) * step]
    out = 'dragon-model-%d.mjs' % (i + 1)
    with open(out, 'w') as f:
        f.write('/* %d of %d of the sculpt, base64. Generated by make-model.py -- do not edit. */\n'
                'export const part = "%s";\n' % (i + 1, n, base64.b64encode(chunk).decode()))
    print('%s  %.2f MB of base64 for %.2f MB of model' % (out, len(open(out).read()) / 1e6, len(chunk) / 1e6))
print('source %s  %.2f MB  sha256 %s' % (src, len(raw) / 1e6, hashlib.sha256(raw).hexdigest()[:16]))
